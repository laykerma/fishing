-- 1. BẢNG NGƯỜI DÙNG & PHÂN QUYỀN (USERS)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  phone TEXT,
  password_hash TEXT,
  role TEXT DEFAULT 'customer', -- 'admin' hoặc 'customer'
  avatar TEXT,
  auth_provider TEXT DEFAULT 'local',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. BẢNG SẢN PHẨM & TỒN KHO (PRODUCTS)
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  price NUMERIC NOT NULL,
  original_price NUMERIC,
  rating NUMERIC DEFAULT 5.0,
  reviews_count INT DEFAULT 1,
  sold_count INT DEFAULT 0,
  badge TEXT,
  badge_color TEXT,
  image TEXT,
  short_desc TEXT,
  target_fish JSONB,
  style TEXT,
  specs JSONB,
  variants JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. BẢNG ĐƠN HÀNG (ORDERS)
CREATE TABLE IF NOT EXISTS public.orders (
  id TEXT PRIMARY KEY, -- Ví dụ: THEO-882314
  customer JSONB NOT NULL,
  items JSONB NOT NULL,
  totals JSONB NOT NULL,
  payment_method TEXT DEFAULT 'cod',
  status TEXT DEFAULT 'pending', -- 'pending', 'processing', 'shipping', 'completed', 'cancelled'
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. BẬT BẢO MẬT ROW LEVEL SECURITY (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 5. CHÍNH SÁCH BẢO MẬT (POLICIES)
-- Cho phép mọi khách xem danh mục sản phẩm công khai
DROP POLICY IF EXISTS "Public can view products" ON public.products;
CREATE POLICY "Public can view products" ON public.products FOR SELECT USING (true);

-- Cho phép khách đặt hàng (Insert order)
DROP POLICY IF EXISTS "Anyone can insert order" ON public.orders;
CREATE POLICY "Anyone can insert order" ON public.orders FOR INSERT WITH CHECK (true);

-- Cho phép xem đơn hàng (Admin xem hết, khách tra cứu theo mã đơn/sđt)
DROP POLICY IF EXISTS "Public can read orders" ON public.orders;
CREATE POLICY "Public can read orders" ON public.orders FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow update orders" ON public.orders;
CREATE POLICY "Allow update orders" ON public.orders FOR UPDATE USING (true);

-- Cho phép đăng ký người dùng mới
DROP POLICY IF EXISTS "Anyone can register" ON public.users;
CREATE POLICY "Anyone can register" ON public.users FOR INSERT WITH CHECK (true);

-- Cho phép đọc thông tin người dùng
DROP POLICY IF EXISTS "Anyone can read user for login" ON public.users;
CREATE POLICY "Anyone can read user for login" ON public.users FOR SELECT USING (true);

-- Cho phép sửa thông tin người dùng
DROP POLICY IF EXISTS "Anyone can update users" ON public.users;
CREATE POLICY "Anyone can update users" ON public.users FOR UPDATE USING (true);

